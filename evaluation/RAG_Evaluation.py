
# Local Ollama LLM use garna
from langchain_ollama import ChatOllama


class RAGEvaluator:

    def __init__(
        self,
        model="llama3:latest",
        temperature=0,
    ):
        # Local Ollama LLM load garne
        self.llm = ChatOllama(
            model=model,
            temperature=temperature,
        )

    def retrieval_precision(
        self,
        relevant_documents,
        retrieved_documents,
    ):
        # Retrieved documents ma kati relevant chan calculate garne
        relevant_retrieved = set(
            relevant_documents
        ).intersection(
            set(retrieved_documents)
        )

        if not retrieved_documents:
            return 0.0

        return (
            len(relevant_retrieved)
            / len(retrieved_documents)
        )

    def retrieval_recall(
        self,
        relevant_documents,
        retrieved_documents,
    ):
        # Relevant documents madhye kati retrieve bhayo calculate garne
        relevant_retrieved = set(
            relevant_documents
        ).intersection(
            set(retrieved_documents)
        )

        if not relevant_documents:
            return 0.0

        return (
            len(relevant_retrieved)
            / len(relevant_documents)
        )

    def evaluate_context_relevance(
        self,
        question,
        context,
    ):
        # Context question ko lagi relevant cha ki chaina evaluate garne
        prompt = f"""
You are evaluating the relevance of retrieved context
for a RAG system.

Question:
{question}

Retrieved Context:
{context}

Determine whether the context contains information useful
for answering the question.

Return only one of these labels:

RELEVANT
NOT_RELEVANT

Evaluation:
"""

        response = self.llm.invoke(prompt)

        return response.content.strip()

    def evaluate_faithfulness(
        self,
        context,
        answer,
    ):
        # Answer context bata supported cha ki chaina evaluate garne
        prompt = f"""
You are evaluating the faithfulness of an answer
generated by a RAG system.

Context:
{context}

Answer:
{answer}

Determine whether the answer is fully supported
by the provided context.

Return only one of these labels:

FAITHFUL
NOT_FAITHFUL

Evaluation:
"""

        response = self.llm.invoke(prompt)

        return response.content.strip()

    def evaluate_answer_relevance(
        self,
        question,
        answer,
    ):
        # Answer le question lai directly address garcha ki gardaina evaluate garne
        prompt = f"""
You are evaluating the relevance of an answer
generated by a RAG system.

Question:
{question}

Answer:
{answer}

Determine whether the answer directly addresses
the question.

Return only one of these labels:

RELEVANT
NOT_RELEVANT

Evaluation:
"""

        response = self.llm.invoke(prompt)

        return response.content.strip()

    def evaluate(
        self,
        question,
        relevant_documents,
        retrieved_documents,
        context,
        answer,
    ):
        # Complete RAG response evaluate garne

        # Retrieval precision calculate garne
        precision = self.retrieval_precision(
            relevant_documents,
            retrieved_documents,
        )

        # Retrieval recall calculate garne
        recall = self.retrieval_recall(
            relevant_documents,
            retrieved_documents,
        )

        # Context relevance evaluate garne
        context_relevance = (
            self.evaluate_context_relevance(
                question,
                context,
            )
        )

        # Faithfulness evaluate garne
        faithfulness = self.evaluate_faithfulness(
            context,
            answer,
        )

        # Answer relevance evaluate garne
        answer_relevance = (
            self.evaluate_answer_relevance(
                question,
                answer,
            )
        )

        # Evaluation results return garne
        return {
            "retrieval_precision": precision,
            "retrieval_recall": recall,
            "context_relevance": context_relevance,
            "faithfulness": faithfulness,
            "answer_relevance": answer_relevance,
        }